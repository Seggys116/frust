#!/usr/bin/env python3
"""Write support/official-components.lock from an official channel manifest.

Usage: lock-official-components.py <channel-rust-VERSION.toml> <manifest-sha256> > support/official-components.lock

The fRust toolchain is built from the same commit as that official release, so the official
rust-std packages (target libraries), rust-docs and rust-src run unchanged with it: `rustc -vV`
is identical. Only the code that links rustc_private (clippy, rustfmt, rust-analyzer and its
proc-macro server) has to be built here, with the fRust compiler.

rust-src (the library sources, same commit) is bundled for rust-analyzer's std macro and
go-to-definition support; its target column is "any".
The manifest hash is checked by the caller against <manifest-url>.sha256.
"""
import sys
import tomllib

# platform -> (host target for host-only components, extra rust-std targets bundled)
BUNDLES = {
    "linux": (
        "x86_64-unknown-linux-gnu",
        [
            "x86_64-unknown-linux-musl",
            "aarch64-unknown-linux-gnu",
            "wasm32-unknown-unknown",
            "wasm32-wasip1",
        ],
    ),
    "macos-aarch64": (
        "aarch64-apple-darwin",
        [
            "x86_64-apple-darwin",
            "aarch64-apple-ios",
            "aarch64-apple-ios-sim",
            "x86_64-apple-ios",
            "aarch64-apple-ios-macabi",
            "x86_64-apple-ios-macabi",
            "wasm32-unknown-unknown",
            "wasm32-wasip1",
        ],
    ),
    "macos-x86_64": (
        "x86_64-apple-darwin",
        [
            "aarch64-apple-darwin",
            "aarch64-apple-ios",
            "aarch64-apple-ios-sim",
            "x86_64-apple-ios",
            "aarch64-apple-ios-macabi",
            "x86_64-apple-ios-macabi",
            "wasm32-unknown-unknown",
            "wasm32-wasip1",
        ],
    ),
}

manifest_path, manifest_hash = sys.argv[1:3]
manifest = tomllib.load(open(manifest_path, "rb"))
print(f"# Official components bundled into the fRust release archives, pinned by sha256.")
print(f"# release {manifest['pkg']['rust']['version']} dated {manifest['date']}; channel manifest sha256 {manifest_hash}")
print("# columns: bundle component target sha256 url   (generated by support/tools/lock-official-components.py)")
for bundle, (host, targets) in BUNDLES.items():
    entries = [("rust-docs", host), ("rust-src", "any")]
    entries += [("rust-std", t) for t in targets]
    for component, target in entries:
        # rust-src is the one target-independent package: the manifest keys it "*".
        pkg = manifest["pkg"][component]["target"]["*" if component == "rust-src" else target]
        assert pkg["available"], (component, target)
        print(f"{bundle} {component} {target} {pkg['hash']} {pkg['url']}")
